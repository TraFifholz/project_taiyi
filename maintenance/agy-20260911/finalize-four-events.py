report = {}
for key, name in names.items():
    src = drafts / f'{key}-{name}-AGY原稿.md'
    text = src.read_text(encoding='utf-8')
    raw_hash = hashlib.sha256(src.read_bytes()).hexdigest()
    for heading, values in zip(('事件前五项','事件后五项'), items[key]):
        body = '\n'.join(f'{i}. {value}' for i, value in enumerate(values,1))
        pattern = r'## ' + heading + r'\s*\n.*?(?=\n#{1,2} |\Z)'
        text, count = re.subn(pattern, '## ' + heading + '\n\n' + body + '\n', text, flags=re.S)
        assert count == 1, (key,heading,count)
    text = re.sub(r'^#{1,2} (?:[ABCD]｜[^\n]*|事件 D：灾备厅决战)\n*', '', text, flags=re.M)
    applied=[]
    for old,new in edits[key]:
        if old in text:
            text = text.replace(old,new)
            applied.append(old[:55])
        elif old != '整个人形残兵':
            raise ValueError(f'{key}: replacement not found: {old}')
    header = f'# {key}｜{name}\n\n> 独立 AGY 扩写，主会话已核对衔接与前后事项；[主持衔接页](README.md)｜[AGY 原稿](../../agy/event-expansion-20260911/{src.name})。\n\n'
    dst = target / f'{key}-{name}.md'
    dst.write_text(header + text.strip() + '\n',encoding='utf-8')
    report[key] = {'draft_sha256':raw_hash,'draft':str(src),'ready':str(dst),'continuity_edits':applied}
(root / 'maintenance/agy-20260911/four-events/continuity-edits.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({key:{'edited_passages':len(value['continuity_edits'])} for key,value in report.items()}))
